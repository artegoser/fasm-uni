    mov ax, 4C00h
    int 21h

; =============================================
; Процедура преобразования байта в строку в двоичном виде
; AL - байт.
; DI - буфер для строки (8 символов). Значение регистра не сохраняется.
;
; Локальные метки (начинаются с точки) и анонимные метки (@@).
; =============================================
byte_to_bin_str:
    push cx
    mov cx, 8

@@:                         ; Анонимная метка (начало цикла)
    rol al, 1
    jc .one                 ; Локальная метка
    mov byte [di], '0'
    jmp .end_iter           ; Переход на конец итерации (локальная метка)

.one:
    mov byte [di], '1'

.end_iter:
    inc di
    loop @b                 ; Переход на анонимную метку @@ (начало цикла)

    pop cx
    ret

; --- Данные ---
buffer db '00000000', '$'   ; 8 символов + терминатор DOS
