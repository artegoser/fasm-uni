use16
org 100h

    ; Пример использования: вывести число 0ABh в двоичном виде
    mov al, 0ABh
    lea di, [buffer]
    call byte_to_bin_str

    ; Вывести строку
    lea dx, [buffer]
    mov ah, 09h
