; Задание 4. Вариант 3.
; k = (a * b) / (b + c)
; a — байт со знаком, b, c — слово со знаком, k — двойное слово со знаком.
; Промежуточные вычисления — 32-битные; нулевой делитель: код завершения 1.

use16
org 100h

    ; --- a * b ---
    movsx eax, [a]
    movsx ebx, [b]
    imul eax, ebx       ; EAX = a * b

    ; --- b + c ---
    movsx ecx, [c]
    add ecx, ebx        ; ECX = b + c, включая сумму вне диапазона слова
    jz .error

    ; --- (a * b) / (b + c) ---
    cdq
    idiv ecx
    mov [k], eax        ; Сохраняем полный результат, включая значения > 32767

    ; --- Завершение программы ---
    mov ax, 4C00h
    int 21h

.error:
    mov ax, 4C01h
    int 21h

; --- Данные ---
a  db -6              ; байт со знаком
b  dw 100             ; слово со знаком
c  dw 50              ; слово со знаком
k  dd 0               ; двойное слово со знаком
