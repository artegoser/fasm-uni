; Задание 4. Вариант 3.
; k = (a * b) / (b + c)
; a — байт со знаком, b, c — слово со знаком, k — двойное слово со знаком.

use16
org 100h

    ; --- a * b ---
    mov al, [a]         ; AL = a (байт со знаком)
    cbw                 ; Расширение знака AL -> AX
    imul word [b]       ; DX:AX = AX * b (32-битный результат)

    ; --- b + c ---
    mov cx, [b]
    add cx, [c]         ; CX = b + c

    ; --- (a * b) / (b + c) ---
    idiv cx             ; AX = (a * b) / (b + c)

    ; Расширяем результат до двойного слова
    cwd                 ; DX:AX = знаковое расширение AX
    mov [k],   ax       ; Младшее слово k
    mov [k+2], dx       ; Старшее слово k

    ; --- Завершение программы ---
    mov ax, 4C00h
    int 21h

; --- Данные ---
a  db -6              ; байт со знаком
b  dw 100             ; слово со знаком
c  dw 50              ; слово со знаком
k  dd 0               ; двойное слово со знаком
