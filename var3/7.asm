; Задание 7. Вариант 3 (N=3).
; x — двойное слово.
; 1) Инвертировать биты N (3), 2N (6), 2N+1 (7).
; 2) Обнулить младший байт.
; 3) Присвоить 1 битам от N до N+4 (3..7) и от 2N до 2N+4 (6..10).
; 4) Результат сохранить в y.
; 5) Инвертировать x.

use16
org 100h

    ; Загрузить x в DX:AX (DX = старшее слово, AX = младшее)
    mov ax, word [x]
    mov dx, word [x+2]

    ; 1) Инвертировать биты 3, 6, 7
    ;    Маска: бит 3 = 08h, бит 6 = 40h, бит 7 = 80h -> C8h
    xor ax, 0C8h

    ; 2) Обнулить младший байт
    and ax, 0FF00h

    ; 3) Установить биты 3..7 и 6..10
    ;    Биты 3..7:  маска = 11111000b = F8h      (в младшем слове)
    ;    Биты 6..10: маска = 0000011111000000b
    ;      биты 6..10 = 0x07C0 (в младшем слове: биты 6..15 -> 0x07C0)
    ;      Бит  6 = 0x0040
    ;      Бит  7 = 0x0080
    ;      Бит  8 = 0x0100
    ;      Бит  9 = 0x0200
    ;      Бит 10 = 0x0400
    ;    Итого: 0x07C0
    ;    Объединённая маска для AX: 0x00F8 | 0x07C0 = 0x07F8
    or ax, 07F8h

    ; 4) Сохранить в y
    mov word [y],   ax
    mov word [y+2], dx

    ; 5) Инвертировать x
    not word [x]
    not word [x+2]

    ; --- Завершение программы ---
    mov ax, 4C00h
    int 21h

; --- Данные ---
x  dd 0ABCDEf12h
y  dd 0
