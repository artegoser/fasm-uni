; Задание 5. Вариант 3.
; Вычислить: (1+2) * (1+2+3) * ... * (1+2+...+n)
; Результат должен помещаться в слово (16 бит без знака, макс. 65535).
;
; Частичные суммы S(k) = k*(k+1)/2:
;   S(2)=3, S(3)=6, S(4)=10, S(5)=15
;   3 * 6 = 18
;   18 * 10 = 180
;   180 * 15 = 2700
;   2700 * 21 = 56700  — помещается в слово
;   56700 * 28 = 1587600 — не помещается!
; Поэтому n = 6.

use16
org 100h

    mov word [result], 1 ; Результат произведения
    mov cx, 1            ; CX = S(1), затем прибавляем k начиная с 2
    mov bx, 2            ; BX = текущее k, начинаем с k=2

.loop:
    add cx, bx           ; CX = S(k) = 1+2+...+k
    cmp bx, [n]
    ja .done             ; Если k > n, выходим

    ; result *= S(k)
    mov ax, [result]
    mul cx               ; DX:AX = result * S(k)
    mov [result], ax

    inc bx               ; k++
    jmp .loop

.done:
    ; Результат в [result]

    mov ax, 4C00h
    int 21h

; --- Данные ---
n      dw 6             ; n = 6 (максимальное, помещающееся в слово)
result dw 0
