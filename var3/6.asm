; Задание 6. Вариант 3 (N=3).
; Два массива 16-битных целых со знаком, одинаковое кол-во элементов
; (хранится в 8-битной переменной без знака).
; Из каждого элемента первого массива вычесть его порядковый номер * N.
; Порядковый номер начинается с 0 (или с 1 — по условию; возьмём с 0).

use16
org 100h

    xor cx, cx
    mov cl, [count]     ; CX = количество элементов
    lea si, [arr1]      ; SI -> первый массив
    xor bx, bx          ; BX = порядковый номер (0, 1, 2, ...)

.loop:
    ; Вычислить номер * N (N=3)
    mov ax, bx
    mov dx, 3           ; N = 3
    imul dx              ; AX = номер * 3

    ; Вычесть из элемента
    sub [si], ax         ; arr1[i] -= i * 3

    add si, 2            ; Следующий элемент (слово = 2 байта)
    inc bx               ; Следующий номер
    loop .loop

    ; --- Завершение программы ---
    mov ax, 4C00h
    int 21h

; --- Данные ---
count db 5                              ; Количество элементов

arr1  dw 10, 20, 30, 40, 50            ; Первый массив
arr2  dw 5,  15, 25, 35, 45            ; Второй массив
