; Задание 9. Вариант 3 (N=3).
; Массив из N+4 = 7 слов без знака.
; Сдвиги: 1-й элемент влево на N\2=1, 2-й вправо (логич.) на 1,
;          3-й влево на 2, 4-й вправо на 2,
;          5-й влево на 3, 6-й вправо на 3,
;          7-й влево на 4.
; Нечётные (1,3,5,7) — влево, чётные (2,4,6) — вправо.
; Количество бит сдвига: N\2 + (i / 2),  i = 0,1,2,...

use16
org 100h

    lea si, [arr]       ; SI -> массив
    mov bx, 7           ; Количество элементов
    xor di, di          ; DI = индекс элемента (0..6)
    mov dl, 1           ; DL = текущее кол-во бит сдвига (N\2 = 1)

.loop:
    mov ax, [si]        ; AX = текущий элемент
    mov cl, dl          ; CL = количество бит сдвига

    test di, 1          ; Проверяем чётность индекса
    jnz .shift_right    ; Нечётный индекс -> сдвиг вправо

    ; Чётный индекс (0,2,4,6) -> сдвиг влево
    shl ax, cl
    jmp .store

.shift_right:
    ; Нечётный индекс (1,3,5) -> сдвиг вправо (логический)
    shr ax, cl

.store:
    mov [si], ax        ; Сохранить результат
    add si, 2           ; Следующий элемент
    inc di              ; Следующий индекс

    ; Увеличивать кол-во бит каждые 2 элемента
    test di, 1
    jnz .no_inc
    inc dl
.no_inc:

    cmp di, bx
    jb .loop

    ; --- Завершение программы ---
    mov ax, 4C00h
    int 21h

; --- Данные ---
arr dw 0FFFFh, 0FFFFh, 0FFFFh, 0FFFFh, 0FFFFh, 0FFFFh, 0FFFFh
